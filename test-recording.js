'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs/promises'),os=require('node:os'),path=require('node:path');
const {recordingRegion,RecordingWriter}=require('./lib/recording');
(async()=>{
  const displays=[{id:1,bounds:{x:0,y:0,width:1920,height:1080}},{id:2,bounds:{x:-1280,y:0,width:1280,height:720}}];
  const region=recordingRegion({x:20,y:30,width:300,height:200},{x:-1280,y:0},displays);
  assert.equal(region.displayId,'2');assert.deepEqual(region.area,{x:20,y:30,width:300,height:200});
  assert.throws(()=>recordingRegion({x:1200,y:0,width:200,height:100},{x:-1280,y:0},displays),/同一块屏幕/);
  assert.throws(()=>recordingRegion({x:NaN,y:0,width:100,height:100},{x:0,y:0},displays),/无效/);
  assert.throws(()=>recordingRegion({x:0,y:0,width:8,height:80},{x:0,y:0},displays),/至少/);
  const dir=await fs.mkdtemp(path.join(os.tmpdir(),'suira-record-writer-'));
  const writer=new RecordingWriter(dir);
  const first=writer.begin();await assert.rejects(writer.begin(),/已有录制/);const session=await first;
  assert.equal(await fs.stat(session.filePath).catch(()=>null),null);
  await assert.rejects(writer.append('wrong',Buffer.from('x')),/结束/);
  await assert.rejects(writer.append(session.id,new ArrayBuffer(0)),/无效/);
  const parts=['EBML','chunk1','chunk2','end'];
  const appends=parts.map(value=>writer.append(session.id,Buffer.from(value)));
  const saved=await writer.finish(session.id);await Promise.all(appends);
  assert.equal(await fs.readFile(saved.filePath,'utf8'),parts.join(''));assert.equal(saved.bytes,parts.join('').length);
  assert.equal(await fs.stat(saved.filePath+'.partial').catch(()=>null),null);
  await assert.rejects(writer.append(session.id,Buffer.from('late')),/结束/);
  const empty=await writer.begin();await assert.rejects(writer.finish(empty.id),/没有生成/);
  assert.equal(await fs.stat(empty.filePath+'.partial').catch(()=>null),null);
  const partial=await writer.begin();await writer.append(partial.id,Buffer.from('recoverable'));await writer.abandon();
  assert.equal(await fs.readFile(partial.filePath+'.partial','utf8'),'recoverable');assert.equal(writer.current,null);
  const pending=writer.begin();const aborted=writer.abandon();await assert.rejects(pending,/取消/);await aborted;
  assert.equal(writer.current,null);
  console.log('PASS 负坐标、多屏边界、非法选区；并发开始互斥、顺序写盘、等待尾块、迟到块拒绝、空视频清理和中断数据保留');
})();
