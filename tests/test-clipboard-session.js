'use strict';
const assert=require('node:assert/strict');const {clipboardTarget,currentPasteTarget}=require('../lib/clipboard-session');
const owner=10,A={hwnd:'101',pid:20,processStartedAt:100,title:'聊天 A'},B={hwnd:'202',pid:30,processStartedAt:200,title:'ChatGPT 当前聊天'},self={hwnd:'303',pid:owner};
const a=clipboardTarget(A,owner),b=clipboardTarget(B,owner);
assert.equal(a.hwnd,'101');assert.equal(b.hwnd,'202');
assert.equal(clipboardTarget(self,owner),null,'自己的窗口不能回退到历史窗口');
assert.equal(clipboardTarget(null,owner),null,'查询失败不能复用旧目标');
assert.equal(clipboardTarget(self,owner,b).hwnd,'202','面板到历史条的本次交接保持当前聊天');
assert.equal(clipboardTarget(B,owner,a).hwnd,'202','实际前台覆盖面板目标');
assert.equal(currentPasteTarget(B,owner,a,true).hwnd,'202','提交时已切到 B，使用 B');
assert.equal(currentPasteTarget(self,owner,b,true).hwnd,'202','历史条临时获焦时使用本次目标');
assert.equal(currentPasteTarget(self,owner,a,false),null,'过期历史条不能沿用旧目标');
assert.equal(currentPasteTarget(null,owner,a,true),null);
console.log('PASS 剪贴板每次绑定当前窗口，面板交接、窗口切换与过期会话不复用旧目标');
